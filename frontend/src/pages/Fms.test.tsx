function mockApi(options: { people?: (typeof person & { operational_selectable?: boolean })[]; history?: number; failWrite?: boolean; pending?: boolean; capacity?: string | null; capacityUnit?: string | null } = {}) {
  const mock = vi.fn((path: string, init?: RequestInit) => {
    if (init?.method === 'POST' || init?.method === 'PATCH') {
      if (options.pending) return new Promise<Response>(() => {})
      if (options.failWrite) return Promise.resolve(jsonResponse({ detail: 'Operación rechazada' }, 409))
      const payload = JSON.parse(String(init.body))
      if (path === '/api/customers') return Promise.resolve(jsonResponse({ ...customer, ...payload, id: 3 }, 201))
      if (path === '/api/circuits') return Promise.resolve(jsonResponse({ ...circuit, ...payload, id: 3 }, 201))
      return Promise.resolve(jsonResponse({ ...operation, ...payload }, 201))
    }
    if (path.startsWith('/api/sectors')) return Promise.resolve(jsonResponse([{ id: 1, name: 'Sector actual', active: true, created_at }]))
    if (path === '/health') return Promise.resolve(jsonResponse({ status: 'ok' }))
    if (path.includes('/settings/')) return Promise.resolve(jsonResponse({ id: 1, prefix: path.includes('activation-number') ? 'ACT' : 'TKT', separator: '-', padding: 6, next_number: 1 }))
    if (path.includes('/cpe-configuration')) return Promise.resolve(jsonResponse({ configuration: '  Configuración literal\n\tCPE' }))
    if (path.includes('operational-detail')) return Promise.resolve(jsonResponse({ circuit, customer, current_capacity: options.capacity === undefined ? '500' : options.capacity, current_capacity_unit: options.capacity === null ? null : options.capacityUnit ?? 'Mbps', initial_activation: operation }))
    if (path.includes('/interventions')) return Promise.resolve(jsonResponse([{ id: 1, activation_id: 1, responsible: person, occurred_at: created_at, created_at, content: 'Trabajo histórico\nSegunda línea' }]))
    if (path.startsWith('/api/activations/')) return Promise.resolve(jsonResponse(operation))
    if (path.includes('/circuits?')) return Promise.resolve(jsonResponse([circuit]))
    if (path === '/api/customers/1') return Promise.resolve(jsonResponse(customer))
    if (path.includes('/cpe-models?')) return Promise.resolve(jsonResponse([]))
    if (path.includes('/service-types?')) return Promise.resolve(jsonResponse([{ ...person, name: 'Internet' }]))
    if (path.includes('/customers?')) return Promise.resolve(jsonResponse([customer]))
    if (path.includes('/responsibles?')) return Promise.resolve(jsonResponse(options.people ?? [person]))
    if (path.includes('/deactivation-reasons?')) return Promise.resolve(jsonResponse([{ ...person, name: 'Falta de pago' }]))
    if (path.includes('/nodes?')) return Promise.resolve(jsonResponse([{ ...person, name: 'Nodo disponible' }]))
    return Promise.resolve(jsonResponse(Array.from({ length: options.history ?? 1 }, (_, index) => ({ ...operation, id: index + 1 }))))
  }); vi.stubGlobal('fetch', mock); return mock
}
